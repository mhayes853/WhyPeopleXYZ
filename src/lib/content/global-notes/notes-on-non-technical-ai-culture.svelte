<p>
  My opinions on how current AI tools are used mostly relate to software
  development and UI/UX design, and I’ll admit that I haven’t addressed
  other creative fields like art.
</p>
<p>
  One thing I’ve noticed is quite the difference in tone between
  software development and non-software development fields. In my case,
  I feel like <em>not using</em> AI is starting to become more and more
  like a sin against humanity, and if anything I’ve felt more guilty for
  <em>not using it</em>. Perhaps that’s because the software industry
  loves fast shipping speeds (probably way too much), and there’s a
  sense of FOMO and social pressure from not shipping faster using AI.
</p>
<p>
  Yet, when I look into more non-software creative fields, I see the
  exact opposite culture. Using AI is essentially a sin against humanity
  in these other fields (especially art), or at least that’s the
  sentiment I’m getting. For instance, I don’t know of a similar
  <a href="https://bsky.app/profile/did:plc:dc63oncxgxguompva43fl4u2">social media account</a>
  that’s literally tagging every piece of commercial software for
  generative AI usage.
</p>
<p>
  To be honest, the list would be incredibly massive, and you can start
  by adding all the companies
  <a href="https://www.ycombinator.com/companies?batch=Fall%202025">here</a>
  and work your way down the other recent batches if you want to create
  such a list. Then make your way to big tech. Of course, many tech
  companies forbid the usage of AI, but most major ones are pushing it.
  It’s not unlikely that the software used to produce these notes has a
  significant amount of AI generated code somewhere, and likewise for
  creating content as a part of the ongoing AI boycotts.
</p>
<p>
  Going back to non-software creative fields, I can understand the
  sentiment against AI. The point of creation is not to let a machine
  generate a bunch of variants, and then to have a human or other AI
  agent pick the best one. That defeats the whole purpose of creation,
  and the speed gains from such a method are more likely to be
  short-term and illusory. Partially because the creative process opens
  new forms of understanding that are lost when the creation is done for
  you, and also partially because creatives actually like their work and
  didn’t sign up to become managers.
</p>
<p>
  In fact, there will likely be significant negative outcomes if we make
  everyone’s job a manager of some kind. For instance, in software
  development there was plenty of research before the AI-era that shows
  how code review was one of the worst places to catch bugs, despite
  developers thinking otherwise. In effect, making all developers “code
  reviewers” is likely to produce <em>worse</em> outcomes over time, not
  better. I imagine the same can be applied to other creative fields.
</p>
<p>
  I will note is that those who use AI uncritically will not be ahead
  for very long if we do things correctly. Partially, this will come
  about when it takes human ingenuity to differentiate a product from
  the competition, and also partially because actual creatives can use
  existing AI tools far more effectively than those without those
  skills.
</p>
<p>
  I’m also going to predict that the ongoing AI boycotts will likely
  have little to no effect on the pace of change going on. There are
  currently trillions of dollars being pushed into generative AI, and
  even an economic bubble burst will likely not entirely stop that
  funding in the long term just like it didn’t stop for the web. For
  better or for worse, it’s here to stay.
</p>
<p>
  As always, I’m going to reiterate and state that the tools drive the
  culture. AI itself has many uses that can enhance the overall output
  of creatives, but the tools have to encourage a style of thinking that
  provide those enhancements instead of automating all creation. This is
  a far more important problem that has devastating consequences if not
  handled properly.
</p>
