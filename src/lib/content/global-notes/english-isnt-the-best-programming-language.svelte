<p>
  English is purely textual; everything around you isn’t. If we can
  define programming as “describing how to do things”, then we all
  “describe how to do things” in the world through more than just
  textual facilities.
</p>
<p>
  The original personal computing was designed with the idea that the
  GUI and textual programming itself were the same thing. Text just
  helps with a certain kind of precision, but other visuals can represent
  more precision in other areas. Interactivity helps with this a bit
  more, as we can learn things by interaction that purely visual-based
  methods cannot teach.
</p>
<p>
  I would think that we would be on a trajectory towards making
  programming not merely the act of writing textual prompts. Perhaps
  using things would also constitute programming them. This would make
  programming much more expressive and precise than describing
  everything through a tiny text box.
</p>
<p><strong>In other words:</strong></p>
<p><code>Interactive + Explorative Environment &gt; English &gt; Ruby</code></p>
