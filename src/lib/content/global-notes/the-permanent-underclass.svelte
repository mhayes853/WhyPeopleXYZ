<p>
  Besides the fact that term “underclass” makes me laugh for some reason
  whenever I pronounce it, this dystopian horror is always ever
  seemingly present. In fact, you have 2 years to escape apparently,
  otherwise you’re screwed forever. Afterwards, all of those who managed
  to escape will build a dedicated zone for all of their underclassmen
  (does this not sound like high school?) that resembles an internment
  camp.
</p>
<p>
  If we take a critical look at these, we see that this term represents
  a kind of invented status of sorts (that is the case in general for
  the term “socio-economical status”). However, I really want to take a
  deeper look at what makes someone part of the “underclass”. Certainly,
  we can all recognize that average citizens in many authoritarian
  regimes have it worse than those in more democratic regimes. Generally
  speaking, authoritarianism has scaling problems in relation to a
  regime that can be broken up into composable parts. This also goes for
  incarcerated people, and I would even wager students in public
  schooling to an extent.
</p>
<p>
  Through society’s definition in this sense, most of the world is
  already part of a global “permanent underclass”. The way of escaping
  it is of course, better thinking, and better ideas. Thomas Paine once
  famously wrote:
</p>
<blockquote>
  <p>
    <em>For as in absolute governments the king imposes the law, so in
      free governments the law ought to impose the king; and there ought
      to be no other.</em>
  </p>
</blockquote>
<p>
  So in a society with a underclass problem, you need better systems
  design to escape it.
</p>
<p>
  Naturally, this was a fancy way of communicating the obvious fact that
  those in charge have to be competent enough not to be tyrannical if we
  want things to pan out well.
</p>
<p>
  Then let’s look at what is tyrannical right now, something that makes
  decisions with no regard for anything but what it deems correct. This
  is most software today. When you ship a new app to the world, all
  users get roughly the same design, have no direct ability to change
  that design for their own purposes, and are forced to adapt it to
  their needs rather than the other way around.
</p>
<p>
  In such a case, the software imposes the law. So you need to flip this
  on its head somehow (“The law imposes the software” sounds a bit
  weird, and suggests that government regulation is the solution which
  isn’t always the right idea.), and in doing so come to an idea in
  which the software is formed by its direct environment rather than in
  an office in San Francisco (unless of course it’s primary use is in an
  office in San Francisco).
</p>
<p>
  Once that is complete, the biggest tyrant in the room is gone, and we
  transition towards seeing ordinary folk solve their own problems with
  software just like with reading, writing, etc. From an intellectual
  standpoint, this raises the entire IQ of society because everyone now
  has new form of input for understanding the world. From a material
  standpoint, this is a massive creation of wealth simply from the new
  things that get invented as a result.
</p>
<p>
  Ironically, LLMs are currently enabling at least a part of this, and
  it’s never been easier than ever to “build something” without much
  knowledge. Though, my bigger concern here is that LLMs themselves are
  incredibly complicated, and there’s too much misinformation running
  around about them as a result. Much of the tooling around LLMs are
  also not enhancing the information or understanding of them either,
  which is quite a difficult path to escape from a mass market
  standpoint. Subsequently, the “AI bubble” is a result of this, but if
  the existing “permanent underclass” expanded it would likely also be
  the result of this.
</p>
<p>
  So in my opinion, the real “permanent underclass” is a society that
  lacks appropriate understanding of what is actually needed. For the
  record, this class does not exclude rich people either, because almost
  certainly they will not have much understanding either. Otherwise,
  they would realize that remaining in perpetual power over their
  underclassmen isn’t a net positive long-term strategy. In other words,
  we all suffer.
</p>
