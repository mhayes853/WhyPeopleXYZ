<p>Ok, another philosophical note. (You’re welcome.)</p>
<p>
  As said in the previous note, spiritual optimism is a general trait of
  superstition, which is a human universal form of thinking. Generally,
  I think deep styles of thinking (engineering, mathematical,
  scientific, physics, creative, etc.) help get around this, but this is
  very hard for people without those backgrounds (which is unfortunately
  most people, who also are likely not the ones reading this). The
  reason I say this is because a style of deep thinking often gives one
  a framework on how to approach evident situations, and such a
  framework is often reasonably (or perhaps
  <a href="https://worrydream.com/refs/Hamming_1980_-_The_Unreasonable_Effectiveness_of_Mathematics.pdf">unreasonably</a>) effective in dealing with those situations.
</p>
<p>
  The effectiveness of the framework is the key to countering
  superstition, because the thought patterns that lead to superstition
  generally aren’t very effective (they wouldn’t be superstitious
  otherwise!). Despite that, even people who have backgrounds in the
  kinds of deep thinking styles I’m referring to still commonly fall for
  superstitions, especially for cases where there may be a mismatch
  between the situation and their familiar thinking styles. In this
  sense, I believe there are still more styles of thinking that need to
  be discovered that have not been discovered yet. Most likely, such
  future thinking styles will be encoded as entirely new fields or
  industries that don’t exist today.
</p>
<p>
  In ~200,000 years of human history, geometry found its roots circa
  70,000 BC, and engineering only really started appearing in 10,000 BC.
  The notion of “science” took a lot longer to appear, only becoming a
  widespread phenomenon starting in the 16th century. It took another 2
  centuries to realize that absolute monarchy wasn’t a good idea to the
  point where it could be replaced with newer democratic systems. At the
  same time, the Industrial Revolutions developed the modern notions of
  work, public education, society, etc. Computing, electricity,
  universal literacy, and the internet only became widespread last
  century, and it’s taken until the present time for modern AI to become
  widespread. Each of these points spawned new fields, industries, and
  subsequent styles of thinking to make the fields and industries work
  in the real world.
</p>
<p>
  We’re still very adolescent when it comes to developing such methods
  of thinking, which is also why I don’t think of “human-level
  intelligence” as a viable end-state for AI (the target is always
  moving, and the current target has many flaws).
  <a href="https://qr.ae/pFHNHk">“Biology and beyond” is where computing needs to be, so this is a
    good way to gauge where a program/system is.</a>
</p>
<p>
  Regardless, the overall point is that to counter Spiritual Optimism,
  you actually need to understand how things work. When you don't
  understand something, you need the inclination to learn rather than
  depend on superstition. New styles of thinking help with that, but
  it's also worth asking how we can cultivate more of the inclination to
  understand things. Either way, superstition is a human universal, so I
  still hold the point that any system designed for humans needs to take
  it into account.
</p>
