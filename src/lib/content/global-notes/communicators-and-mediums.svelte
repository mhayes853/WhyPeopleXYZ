<p>
  In the world, we often value one’s ability via their communication
  skills. That is, the ability to communicate is weighed heavily in
  one’s favor if they can do it. Likewise, not having strong innate
  communication skills acts against a person often in ways they don’t
  understand.
</p>
<p>
  Let’s say I ask you to explain a complex topic to a 5 year old, like
  Albert Einstein wants you to. Your explanation will likely diverge to
  using visuals, and almost certainly not complicated text passages. In
  this case, that would be a good use of your communication skills.
</p>
<p>
  However, if I forbid you from using visuals, what would happen then?
  Chances are, no matter how good of a communicator you are, you will
  struggle with your explanation. 5 year olds don’t have a sophisticated
  vocabulary or much understanding of complex ideas since their brains
  are still developing, so it’s less likely that text passages (which
  are incredibly abstract) will work.
</p>
<p>
  I see this as a problem with common tools like Slack, Github, Zoom,
  Google Docs, Excalidraw, etc. today. If your team uses all of these
  tools, then the entire collective knowledge base held by your team is
  essentially fragmented, and the only way to make any sense of it is
  via good communication. Yet, even the best communicators accidentally
  leave our relevant context, or otherwise mistate things. In my
  experience, a lot of this is merely caused by simply forgetting to add
  those points, or assuming that the audience has that context. The
  latter can be an especially fatal mistake if the assumption is
  incorrect.
</p>
<p>
  This is why I hold the general view that one’s ability to communicate
  is dependent both on their communication skills and the available
  mediums of communication they have. Someone who can draw well, but not
  talk, can draw a picture worth 10,000 words. Take away drawing as an
  available medium, and they can’t communicate all of a sudden.
</p>
<p>
  An interesting fact, we all seem to crave looking at graphs and charts
  today, but did you ever consider how those things were invented? In
  fact, in the nearly 200,000 year observable history of humanity, only
  240 years ago in 1786 did William Playfair invent the modern chart in
  his book <em>The Commercial and Political Atlas</em>.
  <img src="/images/global-notes/communicators-and-mediums-1.png" alt="A graph from William Playfair's book.">
</p>
<p>
  Yes, that means that Newton, the invention of the modern state, the
  Scientific Revolution, and much more were invented without such a
  visual. Yet the key thing to understand here is that mediums like the
  chart enabled far more scientific discoveries in subsequent centuries.
</p>
<p>
  Computing went through this kind of revolution in the 60s and 70s
  through the great research labs of the time (SRI, ARPA, Xerox, etc.),
  and gave rise to the GUI, internet, personal computing, and much more
  that we take for granted today. Though the key thing to understand was
  that those groups had a very different view of computing as do we
  today. Today, we’re obsessed with boosting productivity through
  automating work-related tasks instead of boosting collaboration
  through shared knowledge systems.
</p>
<p>
  However, the thing to realize is how many ideas we’re missing because
  there is no UI for them. If your team uses Slack, Zoom, Github, etc.,
  then you’ve fragmented correlated knowledge across a bunch of isolated
  apps. When 2 people are talking about a feature in Slack, is Slack
  inherently linking the relevant lines of code, analytics, crash
  reports, etc.? Or is it up to one of the those people to add the
  relevant context? What if the relevant information is completely
  external to the team? How does that get linked?
</p>
<p>
  How many ideas are you simply not thinking of because you simply can’t
  see them through the UIs presented by the standard suite of tools?
  What if a different UI could get you to think of the right ideas?
</p>
<p>
  In a world where everyone says its easier than ever to build your own
  tools, I would expect there to be some progress in the near future.
  Your internal recreations of Slack and Zoom into your team’s knowledge
  ecosystem can crash a few times per day, don’t need a fancy UI, and
  don’t need additional people to communicate with any third parties.
</p>
<p>
  From a business competition standpoint, if you only use the standard
  tools of today, then you’re on the same playing field as everyone
  else. It’s now more possible than ever to change that no matter how
  many resources you have.
</p>
