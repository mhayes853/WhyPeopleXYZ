<p>
  <img src="/images/global-notes/computing-culture-origins-1.jpeg" alt="Computing is pop culture. [...] Pop culture holds a disdain for history. Pop culture is all about identity and feeling like you're participating. It has nothing to do with cooperation, the past or the future—it's living in the present. I think the same is true of most people who write code for money. They have no idea where [their culture came from]. -Alan Kay, in interview with Dr Dobb's Journal (2012)">
  Show a random CS major or Software Engineer pictures of Netwon,
  Einstein, and Feynman. Chances are they’ll recognize one of their
  pictures, typically Einstein. These people are world reknowned
  scientists.
</p>
<p>
  Do the same with pictures of Dennis Ritchie, Bjarne Stroustrup, Ken
  Thompson, Brain Kernighan, and Linus Torvalds. Chances are they’ll
  recognize at least one of if not multiple of them if they’re
  interested in their craft. These people are largely responsible for
  the programming languages and operating systems they use.
</p>
<p>
  Now do the same with Alan Kay, Doug Engelbart, Ivan Sutherland, and
  Ted Nelson. In the vast majority of cases that I’ve tried this, no one
  has been able to recognize even one of their pictures as well as their
  names. These people are largely responsible for the fact that they
  even have a laptop, desktop, or phone with the ability to interact in
  an online ecosystem today.
</p>
<p>
  Rather unfortunately, the ideas of the last group that have largely
  been ignored, or butchered when implemented in today’s commercial
  products.
</p>
<p>
  If you take modern “OOP” languages like Java, C++, Kotlin, Swift, etc.
  to be object-oriented, I recommend you really try to understand what
  Kay was getting at with the term “object-oriented” (also look at
  <a href="https://www.youtube.com/watch?v=6orsmFndx_o">Sketchpad</a> by
  Ivan Sutherland).
</p>
<p>
  If you take the web to be a ubiquitous online ecosystem rich with
  discussion, convenience, and collaboration, then I recommend that you
  really look into the work of Doug Engelbart (especially
  <a href="https://www.dougengelbart.org/pubs/augment-3906.html">this</a>), <a href="https://xanadu.com/">Ted Nelson</a>, and
  <a href="https://en.wikipedia.org/wiki/ARPANET">many others</a>.
</p>
<p>
  One modern sucessor to the work of these pioneers is
  <a href="https://worrydream.com/">Bret Victor</a> and
  <a href="https://dynamicland.org/">Dynamicland</a> (which is very
  anti-Vision Pro). In fact, you can find archives of the
  <a href="https://worrydream.com/refs/">work</a> of many of the above
  pioneers on his
  <a href="https://worrydream.com/Links2025/">website</a>.
</p>
