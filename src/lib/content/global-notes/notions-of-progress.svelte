<p>
  Before the eras of the Renaissance and enlightenment, there was little
  to no form of societal progress. That is, people generally died in the
  same environment they grew up in. However, the ideas of renaissance
  and enlightenment eras (eg. Freedom of Speech, Science, Democracy)
  were able to establish stable systems for incremental progress in what
  we call “developed” nations today. That is, people died in a more
  advanced (but not exponentially so) environment that they grew up in.
</p>
<p>
  The last century brought us AI, personal computing, and the internet.
  These themselves were exponential leaps, similar to the printing press
  in the 15th century (which kicked off parts of the Renaissance and
  subsequent Scientific revolutions).
</p>
<p>
  The point here is that we have notions of exponential progress, but we
  don’t have systems in place to drive such progress like we do for
  incremental progress.
</p>
<p>
  Every year, new products will be released in various industries that
  are better than existing products on the market, but that don’t
  fundamentally change the way business is conducted for the better.
</p>
<p>
  The same can’t be said for creating entirely new industries from
  scratch. For instance, ideas in computing today are largely similar to
  the ideas in computing of the 60s and 70s, just with more incremental
  progress (ie. faster hardware, C -&gt; Rust/Zig/Go, etc.). Many
  existing industries have certainly evolved with the advent of
  computing, but the fundamental ideas of those industries remain
  largely the same. Computing itself only provided an increment, though
  more like a +10 rather than a traditional +1.
</p>
<p>
  I have many reasons to suspect why we don’t have a similar system for
  the exponentials, but it’s too much to write about here.
</p>
<p>
  Instead, I’ll leave an observation that exponential progression leaps
  tend to come from solving “non-clear” problems (ie. Needs &gt; wants,
  non-incremental). Nearly all business settings, including startups,
  only tend to succeed when they solve “clear” problems (ie. Wants &gt;
  needs, often incremental). This skews funding towards solving “clear”
  and incremental problems instead of “non-clear” and non-incremental
  problems, which is probably why we haven’t gotten anything like Xerox
  PARC since the 70s.
</p>
<p>
  With all that said, it’s not hard to see a potential reason for why we
  don’t have a system of exponential progress.
</p>
