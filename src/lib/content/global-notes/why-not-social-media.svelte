<p>
  I’m often asked why I’m not hyper active on platforms like X, Threads,
  or Bluesky, and why I’m opting for this global notes style thing
  instead.
</p>
<p>
  The simple answer to this is that all the mainstream social media
  platforms are not designed for real creative expression. They’ve
  adopted the “easy to use, perpetual beginner” mindset, and have
  amplified it across billions of users. This is quite disastrous in my
  opinion.
</p>
<p>
  On this website, I can use whatever HTML, CSS, and JavaScript I want
  to express my work. I can even embed entire
  <a href="https://whypeople.xyz/liquid-glass">interactable programs</a>
  directly into my writing. (I wish to do this more in the future). On
  social media, you’re essentially limited to plain text, video, and
  photos, which is very rigid in comparison, and this is not even taking
  the “algorithm” into account.
</p>
<p>
  I am very fortunate to have had the natural interest in technology and
  software, as well as the natural ability to understand the complex
  abstact concepts that have enabled me to unlock this kind of
  expression in my work. This is not most of the world, and it’s quite
  saddening to see that they get much more limited forms of expression.
</p>
<p>
  Text on a black background, simple photos, and static videos delivered
  to a one-size-fits-all audience and displayed in a 6-inch rectangle
  are not powerful enough mediums to communicate complex ideas that
  determine the direction of society. Much of these ideas rely on trends
  in large complex datasets, or disastrous things we cannot see (eg. The
  climate problem). From a UI design standpoint, static content isn’t
  enough to convey everything that’s needed with this complexity.
</p>
<p>
  Additionally, centralized large-scale algorithms that make the
  decisions on what media to surface are also not ideal when those
  decisions are made based on impulsive trends. Nearly all influential
  media in the world (eg. The US Constitution, “Common Sense”) did not
  use extensive emotional/moral baiting rhetoric to convey their ideas
  in the way we see on social media today. Thomas Paine didn’t need to
  participate in the “attention economy” in writing “Common Sense”,
  which was one of the influential documents in the wake of the American
  Revolution.
</p>
<p>
  It’s true that my “visibility” on this site is far lower than if I
  were more active on social media, but my intention is only merely to
  reach an audience with the capable creative abilities to seek
  something greater. If you’re reading this of your own accord, there’s
  a high chance that you have such ability, and you’re exactly the type
  of person that I’m trying to reach.
</p>
