<p>
  I don’t normally make future predictions (I like to idealize about the
  future instead of predict it), but I will actually make one here.
</p>
<p>
  Right now, there’s a culture going around that small teams are going to
  dominate everything, and that implementation of complex systems will
  become cheap thanks to agents. Today, this seems true, but mainly
  because I think we’re in a transition period more so than the fact that
  systems design is becoming commoditized. If anything, systems design is
  probably becoming <em>less</em> commoditized, especially as systems
  naturally become more and more complex as a result of increased
  ambition.
</p>
<p>
  I’ll illustrate with an example. Boo.com, an e-commerce site from 1999
  that went bust during the dotcom crash (you should also read up on its
  <a
    href="https://archive.nytimes.com/www.nytimes.com/library/tech/00/12/biztech/technology/13sork.html"
    >failure</a
  >), had ~400 employees. In 2022, before the release of ChatGPT, a single
  person could make a similar e-commerce site in a product like Shopify.
  However, there were many more 400+ employee companies in 2022 than there
  were in 1999.
</p>
<p>
  The reason for this is simple: you have to be more ambitious to compete
  at venture scale. If anyone can make an e-commerce site, then you simply
  have to be more ambitious to stand out from the competition. I think the
  rise of many startups in “serious” hard-tech spaces with heavy software
  and machine learning is beginning to show this, as these kinds of
  projects are certainly more ambitious than past startups.
</p>
<p>
  In other words, what I’m saying is that it’s inevitable that
  venture-scale companies will just take on more ambitious work that will
  require the same hundreds or thousands of employees that previous
  venture-scale companies had to hire. In this sense, everything will
  eventually stabilize, and we’ll likely be in a similar place as before
  with regards to organization size and required technical knowledge on
  the job.
</p>
<p>
  When I think of small teams that really changed the course of history in
  computing, I can’t think of a more primordial example than Xerox PARC.
  PARC was not a product team, but rather a research lab that discovered
  many of the ideas that led to commercialized personal computing, the
  internet, etc. However, they never sold a product to the mass market, as
  that effort was done in subsequent decades by more recognizable people
  (Steve Jobs, Bill Gates, etc). (Steve Jobs also infamously visited Xerox
  PARC in the late 70s, which is where the ideas for the Lisa and Macintosh
  stemmed from.) (Also yes, I think PARC was more influential than the big
  AI labs of today so far, but we also haven’t seen how AI has fully
  played out yet.)
</p>
<p>
  In other words, PARC won in the idea and influence space, even though
  Xerox itself never capitalized on their inventions (Alto, Smalltalk,
  Ethernet, etc). However, this is also a pattern that repeats itself
  throughout history. Isaac Newton, Leonardo da Vinci, Socrates, Johannes
  Gutenberg, etc. were all individuals that won in the influence sphere,
  and thus have left a much higher mark than even the most successful
  companies of our time. (Perhaps this is because our modern economic
  system has only been around since the 18th century, and so we may not
  have enough data to compare definitively yet against thousands of prior
  years.)
</p>
<p>
  So I think generally it’s best for smaller teams to optimize for
  memorability over mass production, which I think is generally easier for
  them to do as they have less bureaucracy. Mass production inherently
  requires more “material scale” (i.e. more users, locations, etc.), which
  makes it a game of resources that small teams often lack compared to the
  competition (even with AI).
</p>
