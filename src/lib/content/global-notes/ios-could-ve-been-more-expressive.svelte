<p>
  The Home Screen layout is a simple grid of app icons and widgets. This
  is easy to use, but the expressive power is incredibly limited.
</p>
<p>
  How can one draw relationships between different apps and different
  widgets? Folders exist, but they are merely just another version of
  the Home Screen without widget support. In other words, not very
  expressive.
</p>
<p>
  The Home Screen has been the fundamentally been the same since the
  iPhone 2G in 2007. Certainly, 18 years later should be enough time for
  the vast majority of users to learns to use a more expressive
  interface at the cost of an initial learning curve.
</p>
<p>
  On the surface level, one may ask why they need to draw a bunch of
  complex relationships between various apps. This kind of question is
  exactly the result of the problem I’m getting at here. It implies that
  users don’t see the point in potential expressive power that lets them
  think unthinkable and creative thoughts!
</p>
<p>
  Social media is easy to use, both in creation and consumption, but the
  forms of expression are incredibly limited. Simple video, text, and
  photos have been around for decades, long before personal computing
  was even commercialized. Certainly, a highly interactive multitouch
  display that can now run embedded inference on an enormous corpus of
  information would certainly be able to create new forms of media with
  enhanced expressive power. This didn’t happen, and now we have a
  common term for the end result, “brain rot”.
</p>
<p>
  The problem with only focusing on “easy to use” is that it keeps users
  as perpetual beginners. That is, they learn to appreciate the
  simplicity of the interface rather than learning how to use the
  interface to express their inner creative ideas to the fullest
  potential. The latter requires interface design that goes against many
  principles in the HIG (Apple’s human interface guidelines), and that
  embeds a reasonable learning curve into the interface directly (the
  HIG hates this) to learn the complex interactions.
</p>
<p>
  This last point is hard to do correctly in today’s climate primarily
  because of the culture, but I think it is possible to pull off
  successfully in a commercialized manner. I will be attempting this
  with Mutual Ink in the coming months. I think the first step is
  creating something that is easy to use like everything else, but
  adding explicit steps where the interface can instruct users directly
  on how to use their expressive power more.
</p>
<p>
  Yes, this is “explaining how to use the product” which seems to be
  considered taboo. Yet, great games have been doing this for the
  longest time in subtle ways through signifiers and tutorials that
  blend with the main gameplay, and I think it’s more than doable to
  pull it off in apps too.
</p>
<p>
  Another counterpoint is something along the lines of “I just want to
  send an email” or do some task that is considered to be simple. Most
  often, that simple task is just a digitized form of something that was
  previously done in a more physical manner.
</p>
<p>
  My take on this is to ask whether or not we should be porting previous
  mediums to a new medium. Email may have once been incredibly useful,
  but is it the best way to communicate on a multitouch medium with
  embedded inference on an enormous corpus of information?
</p>
<p>
  What most people really mean when they want to “simple and easy to
  use” is really code word for “I don’t want this thing to be annoying”.
  A well-designed learning curve shouldn’t be annoying, but rather it
  should be fun and engaging!
</p>
<p>
  So here’s my controversial take on this whole topic put into a
  singular quote.
</p>
<p>
  <em>Simple and easy to use tools that don’t require learning creates a
    culture that despises learning. Do we really want that?</em>
</p>
