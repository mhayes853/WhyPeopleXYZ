<p>
  This seems to be an incredibly important term in many retrospects,
  trust with individuals, customers, dependencies, etc.
  <a href="https://www.cs.cmu.edu/~rdriley/487/papers/Thompson_1984_ReflectionsonTrustingTrust.pdf">Reflections on Trusting Trust</a>
  is a paper that every technically inclined person should read, and
  doubly so in today’s agentic age.
</p>
<p>
  That being said, what does it actually mean to trust someone? For me
  at least, I like to think of it as an optimization if we strip away
  any emotional or spiritual semblance from it.
</p>
<p>
  I trust the Swift compiler to produce correct assembly code, I trust
  Codex to write code according to my directions, I trust my teammates
  to keep innovating, I trust experts in scientific fields to give
  accurate information, etc. All of these things can go wrong, and I
  could learn to do each one of those tasks myself if I wanted, however
  it’s just more optimal for me not to.
</p>
<p>
  That being said, trust is a very greedy optimization, and how trust is
  obtained is very different from the implications of the optimization.
  For instance, on a societal level, there’s a growing
  <em>distrust</em> in experts, but that trust is merely transferring to
  another class of experts (ie. Influencers). Influencers often gain
  trust by leveraging the idea that “the other side” is completely
  delusional in some form. This idea of “the other side” is actually a
  flaw carried over from nearly every society in history, which is why
  it’s one of our Human Universals.
</p>
<p>
  Looking at the experts case, we see that many people can only rely on
  experts for basic scientific information. This itself presents a
  problem, because those same people have to vote representatives into
  office who make decisions on scientific policy. Often, those
  representatives lack the scientific knowledge themselves, and by
  necessity they’re also forced to trust an expert.
</p>
<p>
  This is massively inefficient in the same way that scribes had to do
  the writing for everyone in ancient times. People had to trust that
  the scribe would translate their ideas into writing properly, which
  once again is a process that could go severely wrong. Once society
  embraced universal literacy, business, commerce, and culture could
  evolve as a result.
</p>
<p>
  In my opinion, the same needs to happen with many scientific fields,
  and most definitely systems thinking. It would be much more convenient
  for ordinary citizens to design their own systems and experiments for
  their needs rather than trusting another individual or organization of
  experts to do it for them. Something-something scribes are only
  necessary in an illiterate society, and that’s why insurance is a
  powerful business model that chains many people.
</p>
