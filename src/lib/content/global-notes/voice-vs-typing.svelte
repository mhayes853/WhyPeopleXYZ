<p>
  I’ve seen propaganda around voice dictation being faster than typing,
  which is why one should adopt it as their primary input mechanism. A
  few months ago I was like this, but ultimately reverted back to just
  typing everything. There’s 2 reasons for this:
</p>
<ul>
  <li>
    Talking constantly feels more physically tiring on the body than
    typing.
    <ul>
      <li>
        See me after meetings in which I talk a lot. It’s usually harder
        to context switch back to deep work due to the accumulated
        exhaustion.
      </li>
    </ul>
  </li>
  <li>
    I am biased (by evidence of this blog) towards writing, and I’ve
    always been better at communicating complex ideas through writing as
    a result.
  </li>
</ul>
<p>
  Personally, I find it’s often hard to convey many of my more
  contrarian ideas in an oral medium, unless I’m well acquainted with
  the person or group I’m speaking to. Perhaps this is because an oral
  medium tends to give its way more to “System 1” (visceral) kinds of
  thinking than writing which lends its way to more “System 2” (deep)
  thinking. Often, contrarian ideas are not easily accessible in
  visceral mode, because it takes active thought to go against things.
</p>
<p>
  I think another aspect is that writing is also visible. For example, I
  could re-read everything I just wrote before writing this sentence,
  and a pure reader can re-read things as many times as they want.
  Perhaps this feedback is what encourages more “System 2” thinking.
</p>
<p>
  The downside of course is that in theory productivity slows, but I’m
  not so sure by how much in practice when we consider overall
  productivity across a work session. Many of the tasks I give GPT 5.6
  Sol run for at least half an hour, and stem from only a single or
  handful of messages with occassional steering during the task.
  Therefore, I think optimizing my WPM would be less impactful than
  optimizing the model’s throughput (TPS)/token efficiency when we
  consider the overall amount of work being done.
</p>
<p>
  Of course, this is not a piece on whether or not voice interfaces are
  useless, because that is false. A great example of these are "hands
  free" situations, devices which aren't designed to have a keyboard and
  are mostly interacted with ephemerally, or collaborative interfaces.
  My take is mostly based on personal preference towards how I
  communicate with other humans/agents digitally.
</p>
