<p>
  If you’ve been paying attention to Peter Steinberger and the
  commentary around OpenClaw, a common trope is that most (80%) if not
  all apps are supposedly dead. For the record, Peter Steinberger comes
  from the iOS world himself, which I suppose counts as credibility
  here.
</p>
<p>
  In my opinion, as someone who also does app development as a career,
  he’s kind of right if we’re referring to the state of mobile apps
  today. Most apps that just display simple information from an API are
  usually not the hardest things to create, and their UIs are genuinely
  not very inspiring. These kinds of apps can be merged into something
  like OpenClaw through a good API layer.
</p>
<p>
  That being said, we have to remember what the purpose of a good UI is.
  That is, a world of exploration, not just another command center to
  perform some action. Apps with basic charts, graphics, tables, and
  lists are the kind of cases that OpenClaw can and will be able to
  handle in the future.
</p>
<p>
  For the kinds of apps that have a more explorative UI, but not a lot
  of technical complexity (eg. Hardware, Machine Learning, Domain
  Knowledge, Technical Integrations, etc.) can be replicated by a vibe
  coder that has creative tastes. Such a vibe coder can also invent a UI
  specific to their needs, rather than being dependent on someone
  else’s. This alone has cut many of my side project ideas, because
  there’s no point in building something commercially if someone else
  can just vibe code it for their own needs and purposes.
</p>
<p>
  Of course, most vibe coders are not very creative people, and I see
  this as more of a societal issue than an inherent skill issue.
  Additionally, most normies also aren’t going to be vibe coding anytime
  soon either, and will still be perpetual consumers. This means they
  would still benefit from an off-the-shelf solution for many things.
  Though admittedly, this kind of consumption isn’t typically good for
  improving one’s creative abilities, and in fact it will just continue
  to stagnate them.
</p>
<p>
  I think the apps that will still be valuable going forward, will have
  the following 3 traits:
</p>
<ul>
  <li>
    Trust
    <ul>
      <li>Every business needs trust to gain customers.</li>
    </ul>
  </li>
  <li>
    Unique UI
    <ul>
      <li>
        Simple UI elements of today will not be enough here. You need
        something immersive, contrarian, and that doesn’t fit the chat
        UI mold.
      </li>
    </ul>
  </li>
  <li>
    Technical Complexity
    <ul>
      <li>
        This makes it hard to replicate your app, because this is often
        the part that vibe coders with no technical knowledge cannot
        see.
      </li>
      <li>
        Machine learning, Hardware, Domain Expertise, Security,
        Ecosystems, etc.
        <ul>
          <li>
            OpenClaw from a technical standpoint is really an excerise
            in security, I imagine any good engineer would be able to
            create its core given the same time that Peter had (and a
            dedicated vibe coder a very insecure version). Though
            disregarding security, it’s codebase is ~750k LOC, and it
            integrates with so many different things creating a larger
            ecosystem that is incedibly difficult to replicate.
          </li>
        </ul>
      </li>
    </ul>
  </li>
</ul>
<p>
  Generally speaking, increasing all of these 3 things in many cases
  requires going beyond just the app medium, and requires branching out
  your product further. The point is that you need to make your app hard
  to replicate via OpenClaw, Vibe Coding, or whatever else. Part of that
  comes from gaining customers, another from unique interface design,
  and another from deep technical knowledge.
</p>
<p>
  As for myself, I find that I’m distancing myself more and more from
  the mobile app development label as time goes on, and agents are
  starting to accelerate this. In fact, the point of my work is to be
  increasingly general across any kind of system imaginable, apps just
  happen to be the current position of my career. I intend to change
  this as time goes on, even though app development is fun, there’s a
  lot more work to do outside that realm that’s also a lot of fun.
</p>
<p>Ecosystems &gt; Apps</p>
