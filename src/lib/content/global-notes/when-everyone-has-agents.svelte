<p>
  Whenever a new widespread technology comes along, it’s early adopters
  tend to find it incredibly refreshing and useful. In the present time,
  many are still in shock that agents completely changed most
  programming in just the span of a few months. Similarly, the early
  web, social media, the automobile in the 20th century, early computing
  itself, etc. have had similar effects. Their initial users saw that it
  changed everything, and as such used those technologies in their
  present world to do things others couldn’t.
</p>
<p>
  However, the web and social media eventually spread across the globe,
  much of the US population owns an automobile, and nearly everyone in
  developed countries has some sort of computer. In all of these cases,
  the social dynamics shifted from “this is incredible” to “everyone has
  this now, and now we’re stuck with all the issues”. When only 1 in 100
  people own an automobile, traffic laws aren’t necessary, but when at
  least 70 do then you need such laws all of a sudden.
</p>
<p>
  Similar things happened with the web and social media, where both
  mediums became the center of public conversation and most notably your
  data. When only 1 in 100 people use a social media platform, no
  advanced algorithm is necessary, but it is when 95 of those 100 people
  also use social media. When only 1 in 100 people use the web, it’s not
  worth investing resources into advanced analytics/data tracking.
  However, when 99 of those 100 people use the web, such tracking
  becomes increasingly tempting, and even necessary for growth in many
  cases (this obviously does not justify spyware).
</p>
<p>
  When it comes to agents, the only people who I know use them
  extensively are myself and colleagues in the tech industry
  (particularly the bay area). Most of everyone else I know would think
  it’s insane for someone to pay $200 or even $20 a month for your
  coding agent of choice. That is to say, things feel nice because we’re
  very much in the “1 in 100 people” phase, but eventually others will
  catch on. We can only know the true impact of the technology when that
  happens, and whether or not it ends up being a net-positive or
  negative for society.
</p>
<p>
  What will be the final ratio of people who use agents to those who
  don’t? I don’t know, and I also don’t see most people interacting with
  them through TUIs or dev-friendly GUIs (Codex Desktop, T3 Code, etc.)
  like most of us do currently. However, it’s quite possible that we
  currently don’t know or have the compute needs to support 100% of the
  population using agents. Primarily because we don’t know how the rest
  of the population will use them yet, and how we will adapt accordingly
  if so.
</p>
<p>
  Primarily, I think one of the effects that will need to deal with will
  have to do with harmful spam of various kinds. While OpenAI and
  Anthropic will likely have certain guardrails in place, open weight
  models may not, and thus the population would be able to indirectly
  (UIs will hide the model names) spin up Kimi/GLM swarms for
  harassment, bullying, etc. This will likely lead to laws requiring
  guardrails for a model to accessible by the general public.
</p>
<p>
  Another kind of “spam” is simply that the attack surface for many
  pieces of software has never been bigger, and this problem is only
  getting worse with better frontier models. I suspect we’ll need
  entirely new ways of designing systems to keep just this problem
  itself in check, and my theory is that we’ll need systems that are
  capable of changing themselves without human intervention in order to
  do so. Think, if you give an agent a snapshot of any piece of
  software, it can probably find a number of exploits through various
  search and retrieval methods. However, if the software has the ability
  to change itself without intervention, then in theory the exploits
  themselves change rendering ones found by an agent irrelevant.
</p>
<p>
  If this is the case, as well as the emergence of software factories at
  scale, then it’s clear that we’ll be consuming an order of magnitude
  more compute than we currently consuming today. If anything, the
  number of agents that use other agents may be an order of magnitude
  more than the number of humans using agents. This dynanicism could
  lead to new expressive mediums that make people fulfilled, or they
  could turn all existing creative work into souless management of agent
  swarms. Only time will tell.
</p>
<p>
  However, another observation from the general populace is once the
  term “AI” is mentioned at all, the tone of everything shifts much more
  negative and judgemental. I believe this is because the general
  populace sees the term “AI” as meaning “ChatGPT” and other generative
  models replacing all the jobs, and datacenters that consume all the
  water and destroy the environment. This version of “AI” is likely to
  become a major political issue at some point, which could
  significantly shape how agents are used in the future or even the
  broader field of AI that the general populace doesn’t consider in
  their anger.
</p>
<p>
  I’m certain there’s a lot more that I’m missing here, and could be
  getting the shape of the problem and usage wrong altogether. However,
  it’s only possible to judge whether or not AI is a net-positive or
  negative for real once most of the population is using it day-to-day,
  and the various systems that come out of that.
</p>
