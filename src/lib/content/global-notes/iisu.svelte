<p>
  This was a project shared to me by a colleague which I found
  interesting because one of my favority hobbies in 5th grade was
  creating Super Mario World ROM hacks with
  <a href="https://fusoya.eludevisibility.org/lm/">Lunar Magic</a>.
  Also, emulation was the reason that I was also able to enjoy many of
  the earlier Fire Emblem titles, and most notably Genealogy of the Holy
  War.
</p>
<p>
  The main concerns I’ve read, myself included, seems to be the scope of
  the project. The former lead has an animation background, and clearly
  has an eye for aesthetics. Yet, he just announced including a social
  network, eshop, and much more (alongside the launcher) like it was no
  big deal. Since the presentation no longer exists, you can read
  <a href="https://www.androidauthority.com/iisu-presentation-features-3619732/">this</a>
  instead.
</p>
<p>
  My most recent startup experience can be classified like the above
  with a somewhat similarly sized team as iiSU. In my case, we had a
  social fitness network in mind that was focused on physical events, an
  entire dynamic reflection journaling feature, and an entire literature
  narrative as an aesthetics layer (we even had drafts of chapters for
  this!). We got through rolling out the social network part, and a bit
  of the dynamic journaling part before really deciding that users
  actually wanted more of the later. Now we’re in the process of
  pivoting (new website for this will be up soon).
</p>
<p>
  Regardless, it was worth it. I wouldn’t have taken on that project if
  it didn’t have a 90% chance of failure, and there were certainly
  lessons to be learned there from a business standpoint. Yet, the
  crucial thing is that if in theory the idea was executed properly, and
  received in the way we had hoped, then it could have made a
  significant impact on the way people perceived their health.
</p>
<p>
  My philosophy since graduating has subsequently been to take on
  ambitious projects that have a 90% chance of failing, but if in the
  10% chance that it succeeds, then it makes a huge difference.
  <a href="https://github.com/mhayes853/swift-operation">Swift Operation</a>
  was one of those successes in my opinion, and I’ve used it extensively
  on every project I’ve undertaken since its release.
  <a href="https://github.com/mhayes853/swift-cactus">Swift Cactus</a>
  could be another in the future, it’s already gotten recognition from
  the cactus core team, and I’m currently working on making a
  <a href="https://github.com/mhayes853/swift-cactus/pull/38">higher-level framework</a>
  that makes building with local models a lot more powerful than what
  you get with FoundationModels.
</p>
<p>
  Of course, those 2 projects consist of just me in my free time, so the
  scope isn’t nearly as big as my professional work. However, I also
  have other projects of my own in the background that I believe are
  even more ambitious than the 2 above. I hope to have updates on those
  soon.
</p>
<p>
  AFAIK, the primary dev of iiSU’s team seems like they know
  <a href="https://www.patreon.com/cw/SapphireRhodonite">their stuff</a>, and I think it would be theoretically possible for something to
  come out of this even if it isn’t everything that was envisioned in
  the now deleted presentation. At the very least, it seems like an
  interesting project to follow even if I’m not in the target audience.
</p>
