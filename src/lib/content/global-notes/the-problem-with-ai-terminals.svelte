<p>
  Alan's answer to this
  <a href="https://www.quora.com/Can-an-AI-command-line-replace-the-GUI-as-the-primary-user-experience-for-computers-assuming-the-technology-improves-and-irrespective-of-today-s-state">question</a>
  puts more light on what I think regarding general chat interfaces, and
  especially interfaces to agentic tools. One of the main issues being
  the complete lack of visibility, feedback, and also as Alan says,
  exploration (through all senses, which really can be a superset of the
  "visibility" and "feedback" traits). Without such traits, the
  effectiveness of these tools (in their existing forms, irrespective of
  how good the models are) tends to depend on the existing domain
  capabilities of the user, which can be a negative multiplier for more
  incapable users.
</p>
<p>
  In the long term, I don't see this particularly leading to mass good
  outcomes, but rather many bad ones with a few possible good ones from
  necessarily small teams of "responsible" users. This is already
  <a href="https://www.businessinsider.com/uber-coo-andrew-macdonald-ai-token-spending-harder-justify-2026-5">happening</a>
  at organizations that have the means to capture even the best talent.
  (I also think much of this relates to "maintenance" vs "creation"
  mode, of which the former tends to apply more to large companies like
  Uber. In practice, maintenance is more about hardening and making a
  system more robust, which is quite different from writing new
  functionallity from scratch. That is, one cannot fix systems with the
  same mindset used to create them.)
</p>
