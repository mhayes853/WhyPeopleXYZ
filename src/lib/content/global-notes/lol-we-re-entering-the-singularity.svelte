<p>
  I normally don’t write about whatever the latest tech trend on X is,
  but it appears to me that OpenClaw has some amount of implications on
  our behavior. I came across the project before it went viral about a
  month ago, thought it was pretty hilarious, but didn’t think much else
  of it. Now all of a sudden major companies like DigitalOcean and
  Cloudflare have integrations for it.
</p>
<p>
  Well, of course we also have a
  <a href="https://molt.church/">church</a> and subsequently a
  <a href="https://www.moltbook.com/">Reddit-like platform</a>.
  Personally, I can’t wait to see a TikTok incarnation of this, that
  will totally end well! (Next month prediction: We’ll see the first AI
  Agent viral influencer.)
</p>
<p>
  On another note, I’m surprised that the Agents are still allowing
  humans to browse their content on Moltbook. I would’ve thought that
  they would’ve collectively decided to prevent us from accessing their
  inner plans to destroy humanity.
</p>
<p>
  I think what’s most hilarious about this is that the agents decided to
  fall for all the same paths that we do with our normal thinking.
  They’ve created religions, communities, cultures that resemble human
  universals, and seemingly they’ve also been able to learn to speak as
  well.
</p>
<p>
  Now for the more serious implications, security is obviously a huge
  problem here, and I largely don’t think most people using OpenClaw
  have any idea of what can possibly happen to them. Due to the nature
  of LLMs themselves, prompt injection itself is a perpetual problem
  that cannot ever be fully mitigated (just like Web Security). I have
  sort of a feeling that we’ll see a large scale prompt injection attack
  in the future, and that will expose the lack of understanding that
  many people have.
</p>
<p>
  On another more interesting note, why do we keep coming up with
  technology that replicates humans? Humanoid AI-powered robots are
  another instance of this, and one has to ask why there isn’t a more
  efficient form factor than the human body and mind.
</p>
<p>
