<p>
  I’ve been talking about this term I’ve made up to a few people
  recently, so I’ll figure that I’ll define it here in a centralized
  place since there was interest.
</p>
<p>
  Quite simply, it’s formal definition is:
  <em>A large amount of insistence that performing a certain action once
    or repeatedly will produce a specified outcome that cannot be
    universally proven to be solely attributed to the action.</em>
</p>
<p>
  Blindly using AI is currently a great example of this. However, this
  also commonly exists in tech decisions, such as assuming that using
  Rust will solve all of your security problems, or that applying
  certain design patterns will make your codebase better.
</p>
<p>
  So what happens when performing the action doesn’t work, or even
  produces the opposite of the intended result? One of the most common
  rhetorics is to tell the actor that they are simply performing the
  activity wrong (skill issue) or not believing hard enough in the
  “doing” of the action (disbeliever). While this may be true in any
  given scenario, it often misses critical parts of doing proper outcome
  analysis, but often the worst part of this is that it
  <em>discourages</em> finding or doing the necessary critical parts
  during analysis. Furthermore, it may cause more advancements in the
  doing of the problematic action, which is often good, but can make
  things worse culturally if such advancements don’t cover the case for
  why the desired outcome wasn’t achieved.
</p>
<p>
  Of course, this principle goes further than software because it’s
  really an explanation of the general human trait of superstition. This
  kind of thinking has actually played a part in civilizational collapse
  before, one case is the Black Death in 1340s/50s which killed an
  estimated 50% of the European population. In that case, a relatively
  common belief at the time was that those affected by the plague were
  sinners of religious faith being dealt divine punishment by God.
  Furthermore, medieval medecine was based on balancing the 4 humors
  (blood, yellow bile, black bile, phelgm), and further shaped by
  miasma, astrology, and regimen.
</p>
<p>
  Needless to say, these approaches were spiritually optimistic in the
  sense that religious faith would always bring safety during hard
  times, and on the fact that existing medicine was the key to good
  health. However, the spread of more religious faith and improvements
  in humor balancing, though pushed for, weren’t what directly helped
  curb the plague. Rather, it took newer/modern practical public-health
  measures like quaratines to stop much of the spread.
</p>
<p>
  I can keep extrapolating, but I think the point is clear. What is true
  however is that this is a clear problem that must be taken into
  account when it comes to systems design, and especially so for usage
  patterns of AI (see cases of psychosis, extreme subsidization, etc.).
  That is, we cannot prentend like users are logical people who don’t
  believe in absolutely insane things (we all do).
</p>
