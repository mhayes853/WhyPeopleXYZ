<p>
  The biggest reason why I still think today’s code (both reading and
  writing manually at the very least from time to time) is necessary is
  simply to boost understanding of what agents are doing. Therefore, if
  you want to get rid of it entirely without causing catastrophic
  destruction, you need a substitute that provides similar or greater
  levels of systems understanding than it. For the record, not even
  compilers have solved this 100% because viewing (or even writing in
  the case of FFMPEG, Linux Kernel, ONNX, etc.) assembly is still useful
  in some contexts.
</p>
<p>
  Despite that, I think there are many ways to achieve greater
  understanding without today’s code, but it differs from domain to
  domain (eg. UIs and ML Kernels have different needs and programming
  styles). The end result will still be and feel like programming, but
  with different representations more tailored to the problem domain.
  Ideally ones that are more aligned with the advanced thinking styles
  of the problem domain. (eg. Geometric representations for UIs, more
  mathematical/information oriented representations for ML models, etc.)
</p>
<p>
  However, I don’t think today’s code as an art form will disappear. A
  lot of us pre-agents were doing this because of enjoyment for the art
  form, that generally doesn’t just go away all of a sudden.
</p>
