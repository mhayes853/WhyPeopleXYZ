<p>
  Inherently one would consider this note theoretical because it
  discusses ideas instead of being directly applicable to the “real
  world”. This is ironic, because the act of writing, or otherwise
  producing abstract symbology to <em>describe</em> rather than
  <em>do</em> is what creates this distinction.
</p>
<p>
  What further makes this annoying is the idea that “In theory, theory
  and practice are the same, but in practice they are not.” Therefore,
  if I mention that the 2 ideas are the same thing in this note, we’re
  still stuck in theory. In fact, I already referred to them as ideas,
  which inherently puts them on the same base playing field. If I
  instead referred to them as “truths”, then once again we put them on
  the same base playing field.
</p>
<p>
  Another annoyance is the idea that the “real world is messy”, and
  therefore practical solutions must also be “messy” because of this.
  This prevents me from creating a simple vacuum to show how theory and
  practice relate to each other. Of course, this writing is already such
  a simple vacuum, but so is a conversation, social media post/comment,
  any form of communication, etc.
</p>
<p>
  I suppose you can see my annoyances with this line of thinking, and
  what makes things worse is that we tend to dismiss the theoretical
  entirely because of it. However, it’s also my observation that the
  best practitioners that I’ve read in the art of Software had a great
  grasp on both “theoretical” and “practical” ideas, whereas the worst
  only tend to focus on technologies and frameworks deemed as
  “practical”.
</p>
<p>
  In terms of economic value, many would say this distinction between
  theory and practice is massive, and will always use it to lower the
  value of education (theoretical). However, it’s often those who manage
  to apply complex theoretical ideas in practice that make the most
  money, and this is especially true today in the AI era. In fact, the
  theoretical complexity is often used as leverage! 99% of the
  population has never heard of a “transformer”, or probably don’t even
  understand what “deep learning” means at even a basic level. Yet, a
  growing number of those people are using and becoming dependent on
  Claude and other models every day.
</p>
<p>
  To those people, learning “AI” means learning how to use Claude to get
  work done, not learning the underlying principles of deep learning.
  I’ll be countered here with this, “If you don’t work in machine
  learning, then why would you spend time learning deep learning
  principles? How are those principles practical for my purposes?” One
  response could be that it’s great to always have deep knowledge of
  things regardless, and therefore if you have the chance and
  inclination, then you should put the learning hours in.
</p>
<p>
  On the other hand, most people don’t think that way, so I’ll observe
  that the best practitioners tend to know a great deal about at least
  what happens 1 abstraction layer below their practice. That is, people
  who know how to code will likely use agents better than those who
  don’t. Furthermore, those who understand deep learning can tell when
  it is being used for both good and evil, which may or may not align
  with the general public’s perception of the matter.
</p>
<p>
  For those reasons above are why I don’t like the distinction between
  the theoretical and practical. Then the main question becomes, how do
  we bridge the distinction?
</p>
<p>
  To that, my answer is that we look at communication. No, I’m not going
  to say that everyone needs to work on their communication skills,
  though it can’t hurt. Rather, I’m looking at what mediums are
  available to us to communicate ideas. Generally speaking, if a typical
  person (ie. not one that likes abstract ideas) cannot see, feel, or
  experience an idea in a form understandable to them, it might as well
  be both invisible and useless to them.
</p>
<p>
  This is in spite of the fact that such an idea may indeed be useful to
  them in the long term, however it’s understandably quite difficult to
  perceive the long term (even for smart people). By long term, I don’t
  mean a handful of months or a few years, but rather decades. This is
  probably why the only successful predictors of the long-term future
  have been from inventors themselves.
</p>
<p>
  So the right questions to ask would be related to whether or not
  writing, social media, video, photos, etc. are the right way to
  communicate long-term ideas in the first place (this note is ironic in
  that sense). In my view, given how each of these tend to lack context
  of some kind (eg. Writing lacks visuals, visuals lack precision,
  social media lacks any context whatsoever), I would say there’s quite
  a bit of work to be done here. We need to make the invisible visible,
  otherwise the rest of the world doesn’t care.
</p>
