<p>
  Most would say that 2-3 years is long term, I disagree. 2-3 years is
  very little, and I consider it to be short term. Generally, this is
  the frequency in which we get a new tech trend, with agents being our
  current one. Furthermore, cultures only shift slightly in this
  timeframe (mostly toward the incremental trend). Larger culture shift
  itself takes a lot longer, and is necessary for invention to prosper.
</p>
<p>
  For me, long term has to mean decades, because that’s generally how
  long it takes for a culture to completely adopt new ways of thinking
  (and for the old generation to start yelling at clouds apparently)
  required to successfully adopt new inventions. Don Norman notes that
  such a process is roughly 20-30 years (eg. See the HD TV example from
  <em>The Design of Everyday Things</em>), and this is also the
  timeframe that Alan Kay and the rest of Xerox PARC operated on with
  respect to their research (eg. Dynabook was sketched in 1968, laptops
  came in the 90s, and the iPad released in 2010).
</p>
<p>
  Another aspect about focusing on the 20-30 year timeframe is that it
  becomes essentially impossible to predict the state of that future
  from today. If I were to ask you what programming would look like in
  5-10 years, you would probably answer around agents and AI taking over
  things. However, you wouldn’t answer with that if I changed the
  timeframe to 30 years because our culture would be entirely different
  then. Instead, the only way to predict that future is to literally
  invent it if we want to adopt the Alan Kay way of saying things. That
  is, long term predictions are much more about realizing visions rather
  than trying to predict where the current trajectories will take us.
</p>
<p>
  This leads us to the nature of those visions. You may think that it
  would be ideal to draw some sort of futuristic technology, and call it
  the vision. This is fine for the short (0-5 years) or medium term
  (5-10 years) scale, but reminder that the difficulty is dealing with
  the culture. Therefore, I would stand to think that the vision needs
  to be based around an ideal culture instead of an ideal technology.
  For Doug Engelbart, this was the notion of augmenting intellect,
  boosting collective IQ, and improving our ability to improve (if you
  read his
  <a href="https://www.dougengelbart.org/pubs/augment-3906.html">1962 paper</a>, computers are not the central focus).
</p>
