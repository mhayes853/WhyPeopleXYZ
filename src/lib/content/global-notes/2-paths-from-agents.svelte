<p>
  Agents are largely swallowing the need to handwrite typical "glue
  libraries together" kind of application code. This code was never hard
  to write in the first place, a lot of it was tedious, and the true
  hard part was in the thinking/architecting stage. Intent is overall
  easier to communicate to an agent than precision (which is the entire
  point).
</p>
<p>
  One obvious path from this is to fully lean into agents, embrace
  loops, product engineering, etc. to produce new software in a
  factory-like style (or whatever mainstream style comes in the future).
  This will likely be the most common path, because it's the most
  natural step up for most engineers building traditional
  mobile/fullstack apps.
</p>
<p>
  The other is to see that agents can write traditionally tedious code,
  and lean into the fact that you have time to do something harder now
  (ie. Something agents can't replicate with ease). For example, while
  still incredibly useful tools, agents don't replace the need for
  research, have difficulty with performance sensitive/security critical
  code, can't build hardware, and generally don't train ML models. This
  path requires a lot of learning, potentially more than embracing
  agents because it isn't a natural next step for typical application
  devs. As a result, it will likely be less common, but may be
  worthwhile for those who feel that agents have taken away the art of
  coding from them.
</p>
<p>
  That being said, regardless of the path, agentic systems are where
  things are (currently) headed. Therefore, one does need to learn more
  beyond just being a mere consumer of coding agents regardless of the
  path.
</p>
