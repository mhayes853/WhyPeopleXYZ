<p>
  If you’ve been like me and are trying to not be left behind™ , you may
  have heard of a recent development in which the Simpsons have virally
  taken over twitter. If you haven’t heard, and because you absolutely
  will be left behind™ otherwise, it’s called a
  <a href="https://ghuntley.com/loop/">Ralph loop</a>. The idea is quite
  simple, is not tied to any plugin or tool, and consists of running an
  agent in a loop with a fresh context for each iteration. Often, if the
  agent seems to be doing well in this loop, you can leave it
  unsupervised to do its own thing.
</p>
<p>
  However, if you’ve read any of Geoffrey Huntley’s posts, or watched
  some of his talks, you’ll find that he likes to directly point out
  that he, Geoffrey Huntley himself, has killed all of software
  development. So, now that modern software development is $10.42 an
  hour, how could he be wrong about this?
</p>
<p>
  Let’s imagine an existing iterative development process in which
  developers are assigned tickets, and they complete them one at a time
  until the <em>process</em> is finished. Now, normally we’d like to
  think there are no roadblocks, but it turns out they happen all the
  time and intervention is needed. Some tickets get delayed, put on the
  backlog, or even scraped entirely for all sorts of various reasons.
</p>
<p>
  In the case of Ralph Loops, Geoffrey Huntley himself states that you
  must step in and put your engineering hat on when one of these
  roadblocks are encountered. Then supervise the agent for a few more
  iterations before going back to DJ-ing.
</p>
<p>
  So we have a live running process that we need to communicate with to
  get around a road block in its current path. There seems to be a
  required collaboration between machine and human to make this
  communication possible. Therefore, there has to be an interface
  somewhere to do this. The agent is perpetually running in a loop,
  autonomously or not, so any updates to the process that we make will
  therefore be received and implemented pretty quickly.
</p>
<p>
  In other words, this is a form of live programming! It’s a concept
  that was widely important in the 70s at PARC! Smalltalk was such a
  good example of a live programming system, and any change to the code
  would be recompiled into the system incredibly fast. So fast, that the
  change itself would be visible in real time unlike most programs today
  where you would have to recompile and run the entire binary from
  scratch.
</p>
<p>
  Once we start thinking about programming as moving around living and
  real things, a lot of powerful ideas are unlocked. For instance, we
  see how
  <a href="https://whypeople.xyz/processes-are-central-to-programming">programming becomes more about dynamic processes</a>
  rather than manipulating static bits inside data structures. We’ll
  also have to take parallels to the physical world in which beings in
  society can be considered running programs, and how we design
  infrastructure for those programs.
</p>
<p>
  However, I want to make clear that a loop is just one kind of process,
  and that thinking all of software development in terms of mere loops
  is a very limited and short-sighted idea. This isn’t to say that the
  Ralph Loop has no merit, but rather that on its own it’s not even
  close to the style of thinking and operating that is actually needed
  here. I think even Geoffrey would agree with that statement by the
  way.
</p>
<p>
  Us humans are also theoretical biological ralph loops that are always
  running, but we don’t have to repeat very defined processes thanks to
  free will. We generally have to make decisions based on information,
  and we also very much like to say the words “if” and “when”.
</p>
<p>
  How will one orchestrate this for continuously live running agents?
  Well if how we handle the physical world tells us anything, we’ll need
  lots of processes in place. Those processes will further have to be
  compatible with dynamic behavior. Additional processes will also be
  needed to create new processed in a meta-language like fashion.
</p>
<p>
  So there will be quite a lot of software development in fact, because
  inevitably there will be so many edge cases for Ralph loops that we’ll
  need processes to handle them. In other words, at this moment is our
  chance to create a new programming <em>environment</em> (not just
  textual language) that prioritizes processes and building systems
  rather than just enhancing our ability to write text faster.
</p>
<p>
  This last thing is absolutely incredibly important, and messing it up
  can have serious consequences. Anyone responsible for building such a
  system at the bear minimum should take time to understand many of the
  ideas from the pioneers of computing, and absolutely not proceed with
  anything until
  <a href="https://www.dougengelbart.org/pubs/augment-3906.html">this paper</a>
  has been fully read and understood. The last time someone attempted
  this without reading that paper, we got the web and a lot of regret
  from its creator.
</p>
<p>I would rather that not happen this time.</p>
