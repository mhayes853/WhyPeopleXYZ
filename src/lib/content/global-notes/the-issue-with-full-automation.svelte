<p>
  Many seem to describe an ideal world as one that is fully automated,
  which is what this note will disagree with.
</p>
<p>
  Today’s apps are “more automated” than you think. If the user cannot
  directly modify the interface or otherwise utilize the software to
  achieve their goals, then for all intents and purposes their experience
  is 95% automated (the 5% they interact with consists of buttons, text
  fields, gestures, etc.). This is the state of most apps today.
</p>
<p>
  I’ve also brought up the idea of a dynamic UI in previous notes.
  Naively, one would think that this is about the app figuring out the
  user’s context and generating an interface based on that instead of
  showing a prepackaged interface from a designer. Certainly, this
  approach has its advantages, but it also suffers from many of the same
  problems as today’s apps if the user has little direct influence on
  the dynamism.
</p>
<p>
  Contrary to some user interface guidelines out there, I don’t mind and
  actually prefer it if the user has to think when using an interface.
</p>
<p>Generally, there are two kinds of thinking when users use an interface:</p>
<ul>
  <li>How do I use this interface?</li>
  <li>How can I best utilize this interface to perform some task or get some question answered?</li>
</ul>
<p>
  When I say that I prefer it if the user has to think, I mean the second
  kind of thinking. If the user has to think about how to use the
  interface at a basic level, that’s a UX problem. However, the second
  kind of thinking is necessary for building any good creation tool
  (e.g., video editors, agentic harness UIs, etc.), because creators
  certainly want or need to think about their creations (bad things
  happen when they don’t).
</p>
<p>
  In other words, if people cannot collaborate with a system directly,
  that is a bad thing because there will be inevitable friction as a
  result. To that end, I like to state that “automation should serve
  collaboration” as a design principle.
</p>
