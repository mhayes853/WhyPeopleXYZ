<p>
  Right now, the meta seems to be to either implement one kind of
  indexing or the other from the previous note. Nearly all apps these
  days index almost entirely mechanically, but some (eg. Collaborative
  stuff Excalidraw, Google Docs, etc.) are more intuition-based.
</p>
<p>
  Only indexing mechanically takes away understanding or a chance to go
  on a journey to find that understanding (of which the journey itself
  produces learnings). Only indexing based on intuition can potentially
  lead one down a false path, and/or cause them to miss subtle and hard
  to find details. Both extremes lead to a lack of enlightenment in some
  way, mechanical-only leads to pure acceptance of black-boxed
  mechanical-standards, and intuition-only leads to conspiracy theories.
</p>
<p>
  Funnily enough, not being able to understand a black-boxed mechanical
  mechanism also leads to conspiracy theories because the mechanical
  understanding becomes purely intuition-based. So really, black boxes
  can be quite bad for important things, especially when most people are
  not the kind who want or have the time/ability to deep dive and
  understand them.
</p>
<p>
  For example, a lot of LLM-based tools will offer the ability to
  summarize readings, but the problem with these tools is often that
  they encourage the "summary" as a replacement for reading instead of
  an enhancement. An LLM-based summary is mechanical indexing while
  actually reading is intuition-based indexing, so only accepting the
  summary is like treating the actual reading as a black box. Now of
  course, not everything needs to be drawn out to 500 pages, but it's
  also no secret that more capable people are the ones who tend to read
  more.
</p>
