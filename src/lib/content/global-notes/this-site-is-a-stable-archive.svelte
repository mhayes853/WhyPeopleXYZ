<p>
  A very common question I get asked is why I avoid platforms like
  LinkedIn in exchange for putting my thoughts/work this site. Now I'm
  not inherently against using social media in the future despite what
  I've said previous
  <a href="https://whypeople.xyz/global-notes#why-not-social-media-">notes</a>, but I would never treat those as "the profile". LinkedIn will
  eventually fail on a long enough timescale (could be decades), and
  with it any user data it stores will vanish into dust never to be seen
  again. Imagine all of your work that you decided to archive vanishing
  like that. Such is the way of the
  <a href="https://worrydream.com/TheWebOfAlexandria/">Web of Alexandria</a>.
</p>
<p>
  I'm reviving this because of the major
  <a href="https://mrshu.github.io/github-statuses/#about">issues</a>
  that Github has been having recently. The amount of downtime and
  issues can potentially become a serious problem down the line, and
  it's already been problematic for lots of large projects. If the
  ending of Theo's recent
  <a href="https://youtu.be/HuE7OvOckfE?si=9ZGgwzyfeZO1JMT1">video</a>
  where he describes fragmentation plays out, and his theory of there no
  longer being a "singular profile" for any given person is true, then
  the only way to have such a profile is to create your own.
</p>
<p>
  As we can see, if Github continues on its current trend, and more
  people begin migrating away, then anything stored on Github is
  inherently "lost" to more and more people. Eventually, Github will
  fail completely on a long enough timescale (could be decades), and
  with it all of it's repos will vanish. The only way out is to clone
  the repos elsewhere.
</p>
<p>
  The information and code on this site is controlled entirely by me.
  It's not an inherently failable business, and I don't ever intend to
  make it one. I do use Netlify for hosting, and Netlify will eventually
  fail on a long enough timescale like any business, but I will just
  find a different hosting provider in that case. You likely won't even
  notice the disruption if that occurs unless you lurk here endlessly
  like some seem to (you know who you are).
</p>
<p>
  So to reiterate, the reason I put effort into this site compared to
  social media platforms is because I at least know that I can keep this
  up as long as I'm still around.
</p>
