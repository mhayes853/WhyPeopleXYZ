<p>
  Everyone learns to write in school, but not everyone becomes an
  author. Often those who are not authors use writing for their own more
  ephemeral needs.
</p>
<p>
  Anyone can pull out a piece of paper and start sketching, but not
  everyone becomes an illustrator. Often those who aren’t illustrators
  use sketching for their own more ephemeral needs.
</p>
<p>
  Everyone learns basic math in school, but not everyone becomes a
  mathematician. Often those who are not mathematicians use arithmetic
  for their own more ephemeral needs.
</p>
<p>
  Anyone can take pictures with a decent camera using their phone, but
  not everyone becomes a photographer. Often those who are not
  photographers take photos for their own more ephemeral (or
  authentically lasting) needs.
</p>
<p>
  Anyone can build a working software system through vibe coding, but
  not everyone becomes a software engineer. Often those who are not
  software engineers use code for their own more ephemeral needs.
</p>
<p>
  The idea of having amateur creators is not exclusive to AI and vibe
  coding, and in general this democratization of creation is a good
  idea. However, the quality of the creations themselves also have to be
  substantially good, and currently I don’t believe AI is doing this to
  the extent it needs to be.
</p>
<p>
  Partially, this is due to the proliferation of bland chatbot
  interfaces that don’t encourage better thinking, but rather encourage
  outsourcing that thinking instead. Also partially, much of the social
  culture and media coverage that misrepresents AI to key decision
  makers is also problematic. (eg. 90% of code being AI generated does
  not indicate that anywhere even close to 90% of an engineer’s purely
  technical duties have been automated.)
</p>
<p>
  Many others online seem to agree that the outsourcing is a problem.
  Unfortunately, just telling people to stop outsourcing their
  understanding isn’t going to solve this problem in a scalable manner.
  You also need to design tools that don’t encourage such outsourcing,
  but rather augment thinking instead. This will be my intention when
  desiging such tools.
</p>
