<p>
  If you’re a weirdo who spends your time thinking about the state of
  humanity instead of getting real work done, you may have read
  <a href="https://www.darioamodei.com/essay/the-adolescence-of-technology">this</a>.
</p>
<p>
  Now, the title of this note is quite cynical, but it’s really there to
  send a message that thought itself is still in its adolescence despite
  the 200,000 year history of humanity. Really, most of our modern ways
  of thinking were only invented a few hundred years ago, which in
  totallity is not even 1% of our history. If we count artifacts from
  ancient philosophers I suppose, then maybe it accounts for a little
  over 1%.
</p>
<p>
  My last note, perhaps a bit jokingly, was about the “permanent
  underclass”, which in its essence is the end result of the adolescene
  of thinking. A “country full of geniuses in a datacenter” may be able
  to help tackle problems we’ve identified at present (eg. Curing
  cancer), but ultimately they are capped by this adolescence itself.
</p>
<p>
  To bring in something you’ll hear a lot from Alan Kay, what would it
  be like to have an IQ of 200 in the stone age? Alan’s answer assumes
  you would be burned at the stake by your peers, and my answer would be
  that such a person was probably miserable (the happy ones probably
  found ways to isolate themselves from their peers).
</p>
<p>
  Similarly, Leonardo Da Vinci was incredibly intelligent, but sadly
  wasn’t able to invent the automobile. Someone with more normalized
  intelligence on the other hand, Henry Ford, was able to assemble and
  ship millions of automobiles in his era. Simply put, thinking itself
  was more mature in Ford’s era than it was in Da Vinci’s, and so even
  someone with more normalized baseline intelligence could have an
  output that was far greater than a past genius.
</p>
<p>
  The truth of the matter is that many geniuses end up exploring a
  narrow slice of a field that’s already beaten to death as a whole.
  Generally speaking, the founders of said field had far more concerns
  than its more contemporary population. At least I can say that with
  certainty in regards to Alan Kay and Doug Engelbart in the field of UI
  design.
</p>
<p>
  In other words, creating a new field itself is a much harder and more
  substantial task. However, this task is necessary to accelerate the
  maturity of thinking, and I sincerely hope that LLMs help out with
  this.
</p>
<p>
  Right now, there are 3 meta economic systems in place: Capitalism,
  Socialism, and Communism. Much of the discourse on these systems focus
  on universal “x system is better than y system” arguments, but
  virtually none focus on the creation of a new kind of system
  altogether. Given that all of these were invented in more adolescent
  eras of thinking, one has to ask not how to patch existing systems
  through adding or removing government policy, but rather what a
  qualitatively different system looks like.
</p>
<p>
  To get less dystopian for a second, and back to the present state of
  AI. I have no doubt that usage paradigms around LLMs themselves are a
  potential representation of more matured thinking. I think the
  technology is quite fantastic, but I have the opposite view on the
  existing interfaces to the technology.
</p>
<p>
  ChatGPT set a very low bar with its interface (it’s really no better
  than a terminal), and unfortunately the rest of the industry followed
  suit with its design. I personally subscribe to OpenAI not because I
  think ChatGPT and Codex are fantastic tools, but rather because GPT
  itself is a powerful tool.
</p>
<p>To summarize my main issues with today’s interfaces to LLMs:</p>
<ul>
  <li>
    They offer very minimal forms of human input (mostly just text,
    audio, and images).
    <ul>
      <li>
        “Tokens” may be the only thing a model truly understands as an
        input, but that is just an optimization.
      </li>
      <li>
        Similarly, today we program in higher-level languages like C and
        Swift. A compiled binary is just an optimization.
      </li>
    </ul>
  </li>
  <li>
    They offer no built-in feedback or learning that train their users
    to use them more effectively.
    <ul>
      <li>
        One shouldn’t have to consiously learn prompt or context
        engineering through trial and error, the tools should inherently
        guide their users towards better usage.
      </li>
      <li>
        This creates a lot of myths around their inner workings, and
        most users treat the model and inference as a complete black
        box.
        <ul>
          <li>
            If you personally want to uncover the black box for
            yourself, try reading the source code of an
            <a href="https://github.com/cactus-compute/cactus">inference engine</a>
            if you’re a technical person.
          </li>
        </ul>
      </li>
    </ul>
  </li>
  <li>
    There’s often no feedback on the goal you’re trying to achieve with
    the tool until you’ve written and submitted a full prompt.
    <ul>
      <li>
        The terminal is quite the same here. Try seeing how much
        real-time feedback you get (that you’re doing something
        extremely dangerous) in your terminal when you type
        <code>sudo rm -drf /</code>!
        <ul>
          <li>
            That being said, the terminal is extremely productive for
            developers who know how to use it properly, and not so much
            for normies. Notice how that neatly translates into today’s
            world with coding agents.
          </li>
        </ul>
      </li>
    </ul>
  </li>
</ul>
<p>
  All of these traits create the kind of pop-culture we see around LLMs
  today. That is, a mass production of slop instead more so than an
  explosion of new good ideas. That’s not to say that good ideas aren’t
  coming to fruition with the existing interfaces, but rather that the
  existing interfaces themselves are in many cases creating the opposite
  intended effect.
</p>
<p>
  If the medium is the message, then we need a better mediums. A bad
  medium shifts thinking more towards adolescence rather than maturity.
</p>
<p>
  Those who cannot mature thinking are the ones in stuck in the
  “permanent underclass”.
</p>
