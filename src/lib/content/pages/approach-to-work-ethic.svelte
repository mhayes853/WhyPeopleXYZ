  <h1 id="approach-to-work-ethic-" class="title">
    Approach to “Work Ethic”
  </h1>
  <ReadingTime />

  <p><strong>Visions</strong> - not goals, not plans</p>
  <p><strong>Just Doing</strong> - not consistency, not discipline</p>
  <p><strong>Showcases</strong> - not deadlines, not accountability</p>
  <p><strong>Meaning</strong> - not numbers, not just results</p>
  <p>
    <strong>Great Ideas</strong> - not just execution, not just
    implementation
  </p>
  <p>
    <strong>Deep Thinking</strong> - not just action, not quick reactions
  </p>
  <p><strong>Equal Collaboration</strong> - not juniors, not seniors</p>
  <p>
    Though such “nots” may be imposed on me, and it will probably look
    like I’m adhering to them, they are the enemies of great work if I am
    chained to them internally.
  </p>
  <blockquote>
    <p>
      Giving a professional illustrator a goal for a poster usually
      results in what was desired. If one tries this with an artist, one
      will get what the artist needed to create that day. Sometimes we
      make, to have, sometimes to know and express. The pursuit of Art
      always sets off plans and goals, but plans and goals don't
      always give rise to Art. If "visions not goals" opens the
      heavens, it is important to find artistic people to conceive the
      projects.
    </p>
    <p>
      Thus the "people not projects" principle was the other
      cornerstone of ARPA/PARC’s success. Because of the normal
      distribution of talents and drive in the world, a depressingly large
      percentage of organizational processes have been designed to deal
      with people of moderate ability, motivation, and trust. We can
      easily see this in most walks of life today, but also astoundingly
      in corporate, university, and government research. ARPA/PARC had two
      main thresholds: self-motivation and ability. They cultivated people
      who "had to do, paid or not" and "whose doings were
      likely to be highly interesting and important". Thus
      conventional oversight was not only not needed, but was not really
      possible. "Peer review" wasn't easily done even with
      actual peers.
    </p>
    <p>
      The situation was "out of control", yet extremely
      productive and not at all anarchic. "Out of control"
      because artists have to do what they have to do. "Extremely
      productive" because a great vision acts like a magnetic field
      from the future that aligns all the little iron particle artists to
      point to “North” without having to see it. They then make their own
      paths to the future. Xerox often was shocked at the PARC process and
      declared it out of control, but they didn't understand that the
      context was so powerful and compelling and the good will so
      abundant, that the artists worked happily at their version of the
      vision. The results were an enormous collection of breakthroughs,
      some of which we are celebrating today.
    </p>
    <p>
      — Alan Kay
      <a href="https://tinlizzie.org/VPRIPapers/m2004001_power.pdf">(The Power of Context)</a>
    </p>
  </blockquote>
  <p>— 11/15/25</p>
